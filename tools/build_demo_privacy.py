"""Keep the demo's bundled privacy text and public HTML in sync with its policy."""
from pathlib import Path
import argparse
import html
import json
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'docs/product/不写日记demo隐私政策.md'
TARGET = ROOT / 'apps/ohos-diary-core/entry/src/main/ets/privacy/PrivacyContent.ets'


def build():
    source = SOURCE.read_text(encoding='utf-8')
    parts = re.split(r'^## (.+)$', source, flags=re.MULTILINE)
    plain = lambda text: text.replace('**', '').replace('`', '').strip()
    intro = plain(re.sub(r'^# .+\n+', '', parts[0])).replace('  \n', '\n')
    sections = [{'title': parts[i], 'body': plain(parts[i + 1])}
                for i in range(1, len(parts), 2)]
    ets = ('// Generated by tools/build_demo_privacy.py from the approved policy.\n'
           'export interface PrivacySection { title: string; body: string; }\n'
           'export const PRIVACY_INTRODUCTION: string = ' + json.dumps(intro, ensure_ascii=False) + ';\n'
           'export const PRIVACY_SECTIONS: PrivacySection[] = ' + json.dumps(sections, ensure_ascii=False, indent=2) + ';\n')
    blocks = []
    listed = False
    for line in source.splitlines():
        if not line.strip():
            if listed:
                blocks.append('</ul>')
                listed = False
            continue
        value = html.escape(line.strip())
        value = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', value)
        value = re.sub(r'`(.+?)`', r'<code>\1</code>', value)
        if value.startswith('# '):
            blocks.append('<h1>' + value[2:] + '</h1>')
        elif value.startswith('## '):
            anchor = ' id="rights"' if value.startswith('## 6.') else ''
            blocks.append('<h2' + anchor + '>' + value[3:] + '</h2>')
        elif value.startswith('- '):
            if not listed:
                blocks.append('<ul>')
                listed = True
            blocks.append('<li>' + value[2:] + '</li>')
        else:
            blocks.append('<p>' + value + '</p>')
    if listed:
        blocks.append('</ul>')
    page = ('<!doctype html><html lang="zh-CN"><meta charset="utf-8">'
            '<meta name="viewport" content="width=device-width, initial-scale=1">'
            '<title>不写日记demo隐私政策</title><style>'
            'body{margin:0;background:#f7f6f0;color:#30342f;font:17px/1.9 system-ui,"Microsoft YaHei",sans-serif}'
            'main{max-width:860px;margin:44px auto;padding:40px;background:#fff;border:1px solid #dedfd7;border-radius:12px}'
            'h1{font-size:30px;line-height:1.4}h2{font-size:22px;margin-top:36px}li{margin:12px 0}'
            'code{font-size:14px;overflow-wrap:anywhere}p{margin:14px 0}'
            '@media(max-width:600px){main{margin:0;padding:24px;border:0;border-radius:0}h1{font-size:27px}}'
            '</style><main>' + ''.join(blocks) + '</main></html>')
    return ets, page


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--html', type=Path)
    args = parser.parse_args()
    ets, page = build()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != ets:
            raise SystemExit('Bundled demo privacy policy is out of date')
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(ets, encoding='utf-8')
    if args.html:
        args.html.parent.mkdir(parents=True, exist_ok=True)
        args.html.write_text(page, encoding='utf-8')
    print('Demo privacy policy is in sync')
